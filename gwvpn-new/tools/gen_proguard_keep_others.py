"""Перегенерация app/proguard-keep-others.pro

Явный -keep для ВСЕХ пакетов, КРОМЕ com.witvpn.gw.** (протокол GW),
по фактическому списку классов из последнего mapping.txt.

Запускать ПОСЛЕ успешной сборки :app:minifyReleaseWithR8 (или assembleRelease):
    python tools/gen_proguard_keep_others.py

Когда запускать: после добавления/удаления зависимостей или новых
топ-левел пакетов в приложении. Если пакет не попал в keep-файл,
его классы начнут переименовываться R8 вместе с GW.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPPING = os.path.join(ROOT, "app", "build", "outputs", "mapping", "release", "mapping.txt")
OUT = os.path.join(ROOT, "app", "proguard-keep-others.pro")

# Единственный пакет, который НЕ держим (он обфусцируется)
GW_PACKAGE = "com.witvpn.gw"

TLD = {
    "com", "org", "net", "io", "kotlin", "javax", "java",
    "kotlinx", "ru", "me", "de", "fr", "uk", "cn", "jp",
}


def main() -> int:
    if not os.path.exists(MAPPING):
        print("mapping.txt not found, run :app:minifyReleaseWithR8 first")
        return 1

    roots: set[str] = set()
    witvpn_subs: set[str] = set()

    with open(MAPPING, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^([A-Za-z_][\w$]*(?:\.[A-Za-z_][\w$]*)*)\s*->", line)
            if not m:
                continue
            parts = m.group(1).split(".")
            if len(parts) == 1:
                roots.add(parts[0])
            elif parts[0] in TLD:
                if parts[1] == "witvpn":
                    witvpn_subs.add(".".join(parts[:3]))
                else:
                    roots.add(".".join(parts[:2]))
            else:
                roots.add(parts[0])

    lines = [
        "# AUTO-GENERATED by tools/gen_proguard_keep_others.py - DO NOT EDIT.",
        "# Explicit -keep for EVERY package EXCEPT the GW protocol package.",
        f"# {GW_PACKAGE}.** is intentionally NOT kept - it is the only one",
        "# that gets renamed by R8 into junk identifiers.",
        "",
    ]
    for s in sorted(witvpn_subs):
        if s != GW_PACKAGE:
            lines.append(f"-keep class {s}.** {{ *; }}")
    for r in sorted(roots):
        lines.append(f"-keep class {r}.** {{ *; }}")

    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    kept = len([l for l in lines if l.startswith("-keep")])
    print(f"OK: {kept} keep rules -> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
